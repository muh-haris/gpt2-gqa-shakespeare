
import argparse
import hashlib
from pathlib import Path

import torch

from src.config import GPTConfig
from src.generation import generate_tokens
from src.model import GPTLanguageModel
from src.tokenizer import BPETokenizer


ROOT = Path(__file__).resolve().parent
CHECKPOINT = ROOT / "checkpoints" / "gpt_gqa_best.pt"
TOKENIZER_FILE = ROOT / "data" / "processed" / "tokenizer.json"


def main():
    parser = argparse.ArgumentParser(
        description="Generate Shakespeare-style text with GPT-GQA"
    )

    parser.add_argument("--prompt", default="ROMEO:")
    parser.add_argument("--max-new-tokens", type=int, default=100)
    parser.add_argument("--temperature", type=float, default=0.9)
    parser.add_argument("--top-k", type=int, default=40)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--output",
        default="runs/generated/sample.txt",
    )

    args = parser.parse_args()

    if not CHECKPOINT.exists():
        raise FileNotFoundError(
            "Best checkpoint not found. Complete GPT-07 first."
        )

    if not TOKENIZER_FILE.exists():
        raise FileNotFoundError(
            "Tokenizer not found. Run train_tokenizer.py first."
        )

    device = torch.device(
        "cuda" if torch.cuda.is_available() else "cpu"
    )

    checkpoint = torch.load(
        CHECKPOINT,
        map_location="cpu",
        weights_only=True,
    )

    # Ensure the tokenizer matches the one used in training.
    expected_hash = checkpoint.get(
        "fingerprints", {}
    ).get("tokenizer.json")

    if expected_hash is not None:
        actual_hash = hashlib.sha256(
            TOKENIZER_FILE.read_bytes()
        ).hexdigest()

        if actual_hash != expected_hash:
            raise ValueError(
                "Tokenizer does not match the training checkpoint"
            )

    tokenizer = BPETokenizer.load(TOKENIZER_FILE)
    config = GPTConfig(**checkpoint["config"])

    if tokenizer.vocab_size != config.vocab_size:
        raise ValueError("Tokenizer and model vocabulary sizes differ")

    model = GPTLanguageModel(config).to(device)
    model.load_state_dict(checkpoint["model"])
    model.eval()

    prompt_ids = tokenizer.encode(args.prompt)

    generated_ids = generate_tokens(
        model,
        prompt_ids,
        max_new_tokens=args.max_new_tokens,
        temperature=args.temperature,
        top_k=args.top_k,
        seed=args.seed,
    )

    # A generated byte sequence can end mid-UTF-8 character.
    # Replacement decoding keeps the sample displayable.
    text = tokenizer.decode(generated_ids, errors="replace")

    output_file = ROOT / args.output
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(text, encoding="utf-8")

    print(f"Checkpoint step: {checkpoint['step']}")
    print(f"Validation loss: {checkpoint['val_loss']:.4f}")
    print(f"Model parameters: {sum(p.numel() for p in model.parameters()):,}")
    print(f"Device: {device}")
    print(f"Prompt tokens: {len(prompt_ids)}")
    print(f"Generated tokens: {len(generated_ids) - len(prompt_ids)}")

    print("\n--- Generated text ---\n")
    print(text)
    print("\n--- End of sample ---")
    print(f"\nSaved to: {output_file}")


if __name__ == "__main__":
    main()
